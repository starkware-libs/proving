use std::collections::HashMap;

use genco::lang::rust;
use genco::quote;
use itertools::Itertools;
use stwo_cairo_common::prover_types::cpu::M31;

use crate::utils::{AUTOGENERATED_CODE_COMMENT, relation_id_const_name};

pub fn generate_relations_rust_file(relation_ids: &HashMap<String, M31>) -> rust::Tokens {
    let relation_id_consts = relation_ids.iter().sorted().map(|(relation, id)| {
        quote! {
            pub const $(relation_id_const_name(relation)): M31 = M31::from_u32_unchecked($(id.0));
        }
    });

    quote! {
        $(AUTOGENERATED_CODE_COMMENT.to_string())
        #![allow(non_camel_case_types)]
        use stwo::core::fields::m31::M31;
        use stwo_constraint_framework::relation;

        $("// A unique ID for each relation, used to separate tuples of different relations")
        $("// used / yielded using the common lookup elements.")
        $("// These were generated by hashing the relation name.")
        $(for relation_id_const in relation_id_consts join ($['\r']) => $relation_id_const)

        $("// The number of lookup elements computed. These are used by all relations, so the size")
        $("// should be at least the size of the largest relation.")
        $("// Shouldn't be too large, as this many values will be stored in memory.")
        const COMMON_LOOKUP_ELEMENTS_SIZE: usize = 128;
        relation!(CommonLookupElements, COMMON_LOOKUP_ELEMENTS_SIZE);
    }
}
